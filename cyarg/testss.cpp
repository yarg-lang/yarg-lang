const int subsetSize{1000};

void randomWords();

StringStore testSs;
std::vector<std::string> words;


int main(void)
{
    randomWords();
    stringStoreInit(&testSs);

    std::vector<ObjString *> objStrings;

    for (std::string &w : words)
    {
        ObjString *t = new ObjString;
        t->obj.isMarked = true;
        t->chars = strdup(w.c_str());

        ObjString *stored = stringStoreStore(&testSs, t);

        if (stored != t)
        {
            printf("Duplicate Add %s %s\n", t->chars, stored->chars);
            delete t->chars;
            delete t;
        }
        else
        {
            objStrings.push_back(t);
        }
    }

    printf("Length of words:%d length of objStrings:%d\n", (int)words.size(), (int)objStrings.size());

    std::mt19937 gen;
    std::uniform_int_distribution<int> uniform_dist(0, (int)objStrings.size() - 1);
    for (int i{0}; i < 400; i++)
    {
        int r{uniform_dist(gen)};
        ObjString *toFind = objStrings[r];
        std::string s{toFind->chars};
        ObjString *t = stringStoreGet(&testSs, s.c_str());
        assert(s == t->chars);
    }

    // remove one at a time
    while (objStrings.size() > 0)
    {
        std::uniform_int_distribution<int> uniform_dist(0, (int)objStrings.size() - 1);
        int r{uniform_dist(gen)};
        ObjString *toDel = objStrings[r];
        printf("Delete %s\n", toDel->chars);
        toDel->obj.isMarked = false;

        stringStoreDeleteUnmarked(&testSs);

        objStrings.erase(objStrings.cbegin() + r);

        delete toDel->chars;
        delete toDel;
    }

    return 0;
}

